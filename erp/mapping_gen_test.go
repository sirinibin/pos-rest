// TestGenerateAdapterMapping writes the per-field mapping matrix used in
// docs/starterp/ADAPTER_MAPPING.md. It is EMPIRICAL: for every contract
// field it mutates the field on a record read from a real legacy document and
// diffs the legacy payload the adapter would send to the v1 handler, so the
// matrix is always what the code does. Opt-in:
//
//	ERP_TEST_DB=1 ERP_GEN_MAPPING=/tmp/matrix.md ERP_CONTRACT_JSON=…/contract.json go test ./erp/ -run TestGenerateAdapterMapping -count=1
func TestGenerateAdapterMapping(t *testing.T) {
	out, cpath := os.Getenv("ERP_GEN_MAPPING"), os.Getenv("ERP_CONTRACT_JSON")
	if out == "" || cpath == "" {
		checkAdapterMappingDoc(t)
		return
	}
	requireDB(t)
	raw, err := os.ReadFile(cpath)
	if err != nil {
		t.Fatal(err)
	}
	var contract mappingContract
	if err := json.Unmarshal(raw, &contract); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(out, []byte(generateMapping(t, contract)), 0o644); err != nil {
		t.Fatal(err)
	}
}

type mappingContract struct {
	Resources []struct {
		Name   string                 `json:"name"`
		Path   string                 `json:"path"`
		Fields map[string]interface{} `json:"fields"`
	} `json:"resources"`
}

func generateMapping(t *testing.T, contract mappingContract) string {
	t.Helper()
	tok := login(t, fx.AdminEmail)
	req := httptest.NewRequest("GET", "/", nil)
	req.Header.Set("Authorization", "Bearer "+tok)
	c, err := authenticate(req)
	if err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	totals := map[string]int{}
	for _, cr := range contract.Resources {
		path := strings.TrimPrefix(cr.Path, "/v1/")
		res := resourceByPath(path)
		if res == nil {
			fmt.Fprintf(&b, "\n### %s (`/%s`) — NOT MOUNTED\n", cr.Name, path)
			continue
		}
		rows, kind := mapResource(t, c, res, cr.Fields)
		for _, r := range rows {
			totals[r.class]++
		}
		fmt.Fprintf(&b, "\n### %s — `/v1/erp/%s`\n\n%s\n\n", cr.Name, path, kind)
		b.WriteString("| Contract field | Type | Mapping | Class |\n|---|---|---|---|\n")
		for _, r := range rows {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.path, r.typ, r.mapping, r.class)
		}
	}
	var sum []string
	for k, v := range totals {
		sum = append(sum, fmt.Sprintf("%s: %d", k, v))
	}
	sort.Strings(sum)
	head := "<!-- generated by TestGenerateAdapterMapping; do not edit by hand -->\nField totals — " + strings.Join(sum, " · ") + "\n"
	return strings.ReplaceAll(head+b.String(), storeA(), "<storeId>")
}

// resolved at package init, before TestMain moves the cwd to a temp dir
var mappingDocPath, _ = filepath.Abs("../docs/starterp/ADAPTER_MAPPING.md")

var reMatrixRow = regexp.MustCompile("^\\| `([^`]+)` \\| ([^|]+) \\| .* \\| ([a-z]+) \\|$")
var reMatrixRes = regexp.MustCompile("^### (.+) — `/v1/erp/([^`]+)`$")

// parseMappingDoc reads the generated matrix of docs/starterp/ADAPTER_MAPPING.md
// into resource path -> field -> class, plus a contract rebuilt from it.
func parseMappingDoc(t *testing.T) (map[string]map[string]string, mappingContract) {
	t.Helper()
	raw, err := os.ReadFile(mappingDocPath)
	if err != nil {
		t.Fatal(err)
	}
	text := string(raw)
	i := strings.Index(text, "<!-- generated by TestGenerateAdapterMapping")
	if i < 0 {
		t.Fatal("ADAPTER_MAPPING.md has no generated matrix")
	}
	classes := map[string]map[string]string{}
	var contract mappingContract
	var cur map[string]interface{}
	var curPath string
	for _, line := range strings.Split(text[i:], "\n") {
		if m := reMatrixRes.FindStringSubmatch(line); m != nil {
			curPath = m[2]
			cur = map[string]interface{}{}
			classes[curPath] = map[string]string{}
			contract.Resources = append(contract.Resources, struct {
				Name   string                 `json:"name"`
				Path   string                 `json:"path"`
				Fields map[string]interface{} `json:"fields"`
			}{m[1], "/v1/" + curPath, cur})
			continue
		}
		m := reMatrixRow.FindStringSubmatch(line)
		if m == nil || cur == nil {
			continue
		}
		classes[curPath][m[1]] = m[3]
		addSpecPath(cur, m[1], strings.TrimSpace(m[2]))
		if e := mappingEnumHints[curPath+"."+m[1]]; e != nil {
			cur[m[1]].(map[string]interface{})["enum"] = e
		}
	}
	return classes, contract
}

// mappingEnumHints restores contract enums the doc's Type column does not
// show, for fields whose probe value must be one of them.
var mappingEnumHints = map[string][]interface{}{
	"employees.status": {"active", "inactive"},
}

// addSpecPath adds "a.b[].c" with type typ to a contract fields map.
func addSpecPath(fields map[string]interface{}, path, typ string) {
	parts := strings.SplitN(path, ".", 2)
	key := parts[0]
	if len(parts) == 1 {
		fields[key] = map[string]interface{}{"type": typ}
		return
	}
	isArr := strings.HasSuffix(key, "[]")
	key = strings.TrimSuffix(key, "[]")
	sp, _ := fields[key].(map[string]interface{})
	if sp == nil {
		sp = map[string]interface{}{}
		fields[key] = sp
	}
	var sub map[string]interface{}
	if isArr {
		sp["type"] = "array"
		it, _ := sp["items"].(map[string]interface{})
		if it == nil {
			it = map[string]interface{}{"type": "object", "fields": map[string]interface{}{}}
			sp["items"] = it
		}
		sub = it["fields"].(map[string]interface{})
	} else {
		sp["type"] = "object"
		if sp["fields"] == nil {
			sp["fields"] = map[string]interface{}{}
		}
		sub = sp["fields"].(map[string]interface{})
	}
	addSpecPath(sub, parts[1], typ)
}

// checkAdapterMappingDoc regenerates the matrix from the contract fields the
// doc lists and fails when a field's class (mapped/new/computed/server)
// no longer matches what the code does, so the doc cannot silently drift.
func checkAdapterMappingDoc(t *testing.T) {
	requireDB(t)
	want, contract := parseMappingDoc(t)
	if len(contract.Resources) < 40 {
		t.Fatalf("parsed only %d resources from ADAPTER_MAPPING.md", len(contract.Resources))
	}
	got := map[string]map[string]string{}
	var curPath string
	for _, line := range strings.Split(generateMapping(t, contract), "\n") {
		if m := reMatrixRes.FindStringSubmatch(line); m != nil {
			curPath = m[2]
			got[curPath] = map[string]string{}
			continue
		}
		if m := reMatrixRow.FindStringSubmatch(line); m != nil && curPath != "" {
			got[curPath][m[1]] = m[3]
		}
	}
	var drift []string
	for res, fields := range want {
		for f, cls := range fields {
			if g := got[res][f]; g != cls {
				drift = append(drift, fmt.Sprintf("%s.%s: doc says %q, code gives %q", res, f, cls, g))
			}
		}
	}
	sort.Strings(drift)
	if len(drift) > 0 {
		t.Errorf("ADAPTER_MAPPING.md drifted from the adapter (%d fields); regenerate it:\n%s", len(drift), strings.Join(drift, "\n"))
	}
}

type mapRow struct{ path, typ, mapping, class string }

type fieldSpec struct {
	path string
	typ  string
	enum []string
}

func walkSpec(fields map[string]interface{}, prefix string, out *[]fieldSpec) {
	keys := make([]string, 0, len(fields))
	for k := range fields {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	seen := map[string]bool{}
	for _, k := range keys {
		sp, _ := fields[k].(map[string]interface{})
		typ := str(sp["type"])
		if reSeedWH.MatchString(k) { // product stock map keyed by warehouse id
			k = "<warehouseId>"
		}
		p := prefix + k
		if seen[p] {
			continue
		}
		seen[p] = true
		var enum []string
		for _, e := range arr(sp["enum"]) {
			enum = append(enum, str(e))
		}
		if sub, ok := sp["fields"].(map[string]interface{}); ok && len(sub) > 0 {
			walkSpec(sub, p+".", out)
			continue
		}
		if it, ok := sp["items"].(map[string]interface{}); ok {
			if sub, ok := it["fields"].(map[string]interface{}); ok && len(sub) > 0 {
				walkSpec(sub, p+"[].", out)
				continue
			}
		}
		*out = append(*out, fieldSpec{p, typ, enum})
	}
}

func unwrapLegacy(be Backend) (*legacyBackend, *nativeBackend, string) {
	switch v := be.(type) {
	case *legacyBackend:
		return v, nil, ""
	case *storesBackend:
		return v.legacyBackend, nil, ""
	case *usersBackend:
		return v.legacyBackend, nil, ""
	case *warehousesBackend:
		return v.legacyBackend, nil, "plus a virtual read-only warehouse `ms_<storeId>` = the legacy `main_store` stock bucket (warehouse_id null)"
	case *stockTransfersBackend:
		return v.legacy, nil, "status `pending` transfers live in `" + v.pending.coll + "` (no legacy equivalent: legacy transfers move stock immediately); completing one creates the legacy `stocktransfer` (new id, `replacedId` = pending id)"
	case *rolesBackend:
		return nil, v.custom, "system roles are built in (read-only); legacy `user_role` documents are listed read-only; custom roles are stored in `" + v.custom.coll + "` (main DB)"
	case *nativeBackend:
		return nil, v, ""
	}
	return nil, nil, ""
}

