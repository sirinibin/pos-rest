// pickOther returns a, or b when the field already holds a (an earlier test
// may have left the probe value behind, which would hide the mapping).
func pickOther(cur, a, b string) string {
	if cur == a {
		return b
	}
	return a
}

func probeValue(fs fieldSpec, cur interface{}) (interface{}, bool) {
	last := fs.path[strings.LastIndex(fs.path, ".")+1:]
	last = strings.TrimSuffix(last, "[]")
	if len(fs.enum) > 0 {
		for _, e := range fs.enum {
			if e != str(cur) {
				return e, true
			}
		}
	}
	switch v := cur.(type) {
	case bool:
		return !v, true
	case float64:
		return v + 1, true
	case int64:
		return float64(v) + 1, true
	case []interface{}:
		if strings.HasSuffix(last, "Ids") {
			return append(append([]interface{}{}, v...), refCandidates(last)[0]), true
		}
		return append(append([]interface{}{}, v...), "probe"), true
	case M:
		return nil, false
	}
	s := str(cur)
	switch {
	case strings.Contains(fs.typ, "datetime") || reDT.MatchString(s):
		return "2025-03-04T05:06", true
	case reDay.MatchString(s) || strings.HasSuffix(last, "Date") && !strings.Contains(fs.typ, "number"):
		return "2025-03-04", true
	case strings.HasSuffix(last, "Id") && last != "keyId" && last != "pcsid":
		for _, cnd := range refCandidates(last) {
			if cnd != s {
				return cnd, true
			}
		}
		return nil, false
	case strings.Contains(fs.typ, "number") || strings.Contains(fs.typ, "integer"):
		return num(cur) + 1, true
	case fs.typ == "boolean":
		return !boolv(cur), true
	case strings.Contains(strings.ToLower(last), "phone") || strings.HasPrefix(last, "mob"):
		return pickOther(s, "0551112223", "0551112224"), true
	case strings.Contains(strings.ToLower(last), "email"):
		return pickOther(s, "probe@t1.example", "probe2@t1.example"), true
	case last == "vatNo":
		return pickOther(s, "399999999900003", "399999999800003"), true
	case last == "crNo":
		return pickOther(s, "2020202020", "2020202021"), true
	case strings.HasPrefix(fs.typ, "array"):
		return []interface{}{"probe"}, true
	}
	if s == "" {
		return "Probe", true
	}
	return s + "Z", true
}

// setPath sets a dotted path ("items[].qty" → first element) on a deep copy.
func setPath(m M, path string, v interface{}) bool {
	parts := strings.Split(path, ".")
	cur := m
	for i, p := range parts {
		isArr := strings.HasSuffix(p, "[]")
		key := strings.TrimSuffix(p, "[]")
		if i == len(parts)-1 && !isArr {
			cur[key] = v
			return true
		}
		if isArr {
			a := arr(cur[key])
			if len(a) == 0 {
				return false
			}
			el := normDoc(a[0])
			na := append([]interface{}{el}, a[1:]...)
			cur[key] = na
			if i == len(parts)-1 {
				return false
			}
			cur = el
			continue
		}
		nx := normDoc(cur[key])
		cur[key] = nx
		cur = nx
	}
	return false
}

func getPath(m M, path string) interface{} {
	parts := strings.Split(path, ".")
	var cur interface{} = m
	for _, p := range parts {
		mm, ok := cur.(M)
		if !ok {
			return nil
		}
		key := strings.TrimSuffix(p, "[]")
		cur = mm[key]
		if strings.HasSuffix(p, "[]") {
			a := arr(cur)
			if len(a) == 0 {
				return nil
			}
			cur = normDoc(a[0])
		}
	}
	return cur
}

func deepCopy(m M) M {
	b, _ := json.Marshal(m)
	var out M
	_ = json.Unmarshal(b, &out)
	return normNumbers(out).(M)
}

// diffPaths lists the dotted paths (array index → []) where a and b differ.
func diffPaths(a, b interface{}, prefix string, out map[string]bool) {
	am, aok := a.(M)
	bm, bok := b.(M)
	if aok && bok {
		keys := map[string]bool{}
		for k := range am {
			keys[k] = true
		}
		for k := range bm {
			keys[k] = true
		}
		for k := range keys {
			p := k
			if prefix != "" {
				p = prefix + "." + k
			}
			diffPaths(am[k], bm[k], p, out)
		}
		return
	}
	aa, aok := a.([]interface{})
	ba, bok := b.([]interface{})
	if aok && bok && len(aa) == len(ba) {
		for i := range aa {
			diffPaths(aa[i], ba[i], prefix+"[]", out)
		}
		return
	}
	ja, _ := json.Marshal(a)
	jb, _ := json.Marshal(b)
	if string(ja) != string(jb) {
		out[prefix] = true
	}
}

func mapResource(t *testing.T, c *Ctx, res *Resource, fields map[string]interface{}) ([]mapRow, string) {
	var specs []fieldSpec
	walkSpec(fields, "", &specs)
	lb, nb, note := unwrapLegacy(res.Backend)
	var rows []mapRow
	if lb == nil {
		coll := "?"
		if nb != nil {
			coll = nb.coll
		}
		kind := fmt.Sprintf("**New adapter collection** `%s` (%s DB) — no legacy equivalent; every field is stored as sent. %s", coll,
			map[bool]string{true: "main", false: "store"}[nb != nil && nb.org], note)
		for _, fs := range specs {
			cls, mp := "new", "`"+coll+"."+strings.ReplaceAll(fs.path, "[]", "[]")+"`"
			if serverOwned[strings.Split(fs.path, ".")[0]] {
				cls, mp = "server", "envelope / server-owned"
			}
			rows = append(rows, mapRow{fs.path, fs.typ, mp, cls})
		}
		return rows, kind
	}
	db := "store DB"
	if lb.inMain || lb.mainOrg {
		db = "main DB"
	}
	kind := fmt.Sprintf("**Legacy** %s — collection `%s` (%s). Writes go through the existing v1 handlers%s.", res.Legacy, lb.coll, db,
		map[bool]string{true: "", false: " (read-only resource)"}[lb.v1.create != nil || lb.v1.update != nil])
	var ops []string
	if lb.noDelete != "" {
		ops = append(ops, "DELETE → 409 unsupported_legacy: "+lb.noDelete)
	}
	if lb.noRestore != "" {
		ops = append(ops, "restore → 409: "+lb.noRestore)
	}
	if lb.noUpdate != "" {
		ops = append(ops, "PATCH/PUT of mapped fields → 409: "+lb.noUpdate)
	}
	if lb.adapterSoftDelete {
		ops = append(ops, "soft delete kept in `erp.del` (legacy delete is destructive; `?hard=1` calls it)")
	}
	if lb.readOnly {
		ops = append(ops, "read-only")
	}
	if note != "" {
		ops = append(ops, note)
	}
	if len(ops) > 0 {
		kind += "\n\n- " + strings.Join(ops, "\n- ")
	}
	storeHex, sample := sampleDoc(t, c, res, lb)
	var rec0 M
	x := newMapCtx(c, storeHex)
	if sample != nil {
		rec0 = deepCopy(lb.toC(x, sample))
	}
	for _, fs := range specs {
		top := strings.Split(strings.TrimSuffix(strings.Split(fs.path, ".")[0], "[]"), "[")[0]
		row := mapRow{path: fs.path, typ: fs.typ}
		switch {
		case fs.path == "storeId":
			row.class, row.mapping = "mapped", "`store_id` (also selects the store database `store_<id>`)"
		case fs.path == "roundingAuto":
			row.class, row.mapping = "mapped", "`erp.x.roundingAuto`; the adapter computes the rounding and sends it as explicit `rounding_amount` (`auto_rounding_amount` false)"
		case top == "zatca" && res.Path != "stores" && !(lb.known[top] && lb.hybrid[top]):
			row.class, row.mapping = "computed", "server-owned: legacy `zatca.*` / `uuid` / `hash` / `prev_hash` / `invoice_count_value` (existing ZATCA flow)"
		case serverOwned[top]:
			row.class = "server"
			row.mapping = map[string]string{"id": "`_id` (hex; client ids kept as alias `erp.cid`)", "version": "`erp.v` (else derived from `updated_at`)",
				"history": "`erp.h` (else synthesized from legacy audit fields)", "createdAt": "`created_at`", "updatedAt": "`updated_at`",
				"createdBy": "`created_by_name` / `erp.cb`", "updatedBy": "`updated_by_name`", "deleted": "`" + nz(lb.deletedKey, "erp.del") + "` (`erp.del` when the legacy delete is destructive)"}[top]
		case !lb.known[top]:
			if rec0 != nil && getPath(rec0, fs.path) != nil && !lb.hybrid[top] {
				row.class, row.mapping = "computed", "read-only, derived from the legacy document"
			} else {
				row.class, row.mapping = "new", "`erp.x."+fs.path+"` (adapter extras; round-trips, invisible to the old app)"
			}
		default:
			row.class, row.mapping = probeField(t, x, lb, sample, rec0, fs, top)
			if lb.hybrid[top] && row.class == "mapped" {
				row.mapping += " (+ full object kept in `erp.x." + top + "`)"
			}
		}
		rows = append(rows, row)
	}
	return rows, kind
}

func nz(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

func probeField(t *testing.T, x *mapCtx, lb *legacyBackend, sample, rec0 M, fs fieldSpec, top string) (string, string) {
	if lb.toL == nil {
		if getPath(rec0, fs.path) != nil {
			return "computed", "read from legacy (read-only resource)"
		}
		return "computed", "read-only resource"
	}
	if sample == nil || rec0 == nil {
		return "mapped", "mapped (no sample document to probe)"
	}
	cur := getPath(rec0, concrete(fs.path))
	val, ok := probeValue(fs, cur)
	if !ok {
		return "mapped", "mapped (not probed)"
	}
	rec1 := deepCopy(rec0)
	if !setPath(rec1, concrete(fs.path), val) {
		return "mapped", "mapped (empty in sample, not probed)"
	}
	ch := map[string]bool{top: true}
	a, errA := lb.toL(x, deepCopy(rec0), sample, ch, false)
	bb, errB := lb.toL(x, rec1, sample, ch, false)
	if errA != nil || errB != nil {
		e := errB
		if e == nil {
			e = errA
		}
		msg := e.Error()
		if ae, ok := e.(*APIError); ok && len(ae.Fields) > 0 {
			var fsx []string
			for k, v := range ae.Fields {
				fsx = append(fsx, k+": "+v)
			}
			sort.Strings(fsx)
			msg = strings.Join(fsx, "; ")
		}
		return "mapped", "mapped, validated (probe rejected: " + strings.ReplaceAll(truncate(msg, 120), "|", "/") + ")"
	}
	diffs := map[string]bool{}
	diffPaths(normDoc(a), normDoc(bb), "", diffs)
	if len(diffs) == 0 {
		if cur != nil {
			return "computed", "read from legacy; not written by the adapter"
		}
		return "mapped", "accepted; no legacy effect for this value"
	}
	var ps []string
	for p := range diffs {
		ps = append(ps, "`"+p+"`")
	}
	sort.Strings(ps)
	if len(ps) > 6 {
		ps = append(ps[:6], "…")
	}
	return "mapped", strings.Join(ps, ", ")
}
